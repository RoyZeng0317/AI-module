const { chromium } = require('C:/Users/roy/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const out = __dirname;
(async () => {
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 900}});
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  let conversations = [];
  const requests = [];
  await page.route('**/api/**', async route => {
    const req = route.request(), url = new URL(req.url()), method = req.method();
    const endpoint = url.pathname.split('/api/')[1];
    let data = {};
    if (endpoint === 'commands') data = {commands: ['model', 'help', 'clear'], arg_suggestions: {model: ['auto','sinco','code','nvidia']}};
    else if (endpoint === 'gpu_info') data = {available: true, name: 'RTX 4060', total_memory_mb: 8192};
    else if (endpoint === 'conversations' && method === 'POST') {
      data = {id: String(conversations.length + 1), title: '新對話', messages: []}; conversations.unshift(data);
    } else if (endpoint === 'conversations') data = conversations;
    else if (endpoint === 'chat') {
      const body = req.postDataJSON(); requests.push(body);
      const conv = conversations.find(c => c.id === body.conversation_id);
      const reply = '這是一段版型驗證回覆。\n\n' + '測試長對話的閱讀寬度與捲動位置。'.repeat(80);
      conv.messages.push({role: 'user', content: body.message}, {role: 'assistant', content: reply});
      conv.title = '介面驗證對話'; data = {reply, trace: []};
    } else if (endpoint.startsWith('conversations/')) data = conversations.find(c => c.id === endpoint.split('/')[1]) || {};
    await route.fulfill({json: data});
  });
  try {
    await page.goto('http://127.0.0.1:8765/web/admin/frontend/src/components/index.html');
    await page.locator('#chatInput').waitFor({timeout: 60000});
    await page.getByText('後端已連線', {exact: true}).waitFor({state: 'attached'});
    await page.screenshot({path: path.join(out, 'desktop-home.png')});
    const home = await page.locator('#chatForm').boundingBox();
    await page.locator('#headerModelBtn').click();
    await page.locator('#modelSelect').selectOption('sinco');
    assert((await page.locator('#headerModelBtn').innerText()).includes('sinco'));
    await page.locator('#settingsModal .overlay-close').click();
    await page.locator('#chatInput').fill('/model ');
    await page.locator('#cmdMenu').waitFor({state: 'visible'});
    await page.locator('#chatInput').press('Escape');
    assert(!(await page.locator('#cmdMenu').isVisible()));
    await page.locator('#chatInput').fill('請說明這次調整');
    await page.locator('#chatInput').press('Enter');
    await page.getByText('這是一段版型驗證回覆。', {exact: true}).waitFor();
    await page.locator('#chatSend').waitFor({state: 'visible'});
    const chatting = await page.locator('#chatForm').boundingBox();
    assert(chatting.y > home.y + 40, 'Composer should move from centered home to bottom');
    assert(requests.length === 1, 'One request per message');
    assert(requests[0].force_mode === 'sinco', 'Header model selects real request mode');
    await page.screenshot({path: path.join(out, 'desktop-chat.png')});
    await page.locator('#sidebarToggle').click();
    assert(!(await page.locator('#sidebar').isVisible()), 'Desktop sidebar should collapse');
    await page.locator('#sidebarToggle').click();
    await page.locator('#btnNewChat').click();
    await page.locator('#chatEmpty').waitFor();
    await page.setViewportSize({width: 390, height: 844});
    await page.screenshot({path: path.join(out, 'mobile-home.png')});
    assert(!(await page.locator('#sidebar').isVisible()), 'Mobile sidebar starts closed');
    await page.locator('#sidebarToggle').click();
    assert(await page.locator('#sidebar').isVisible(), 'Mobile sidebar opens');
    await page.screenshot({path: path.join(out, 'mobile-sidebar.png')});
    await page.keyboard.press('Escape');
    assert(!(await page.locator('#sidebar').isVisible()), 'Escape closes mobile sidebar');
    assert(await page.locator('#sidebarToggle').getAttribute('aria-expanded') === 'false');
    assert(await page.locator('#exportMdBtn svg').isVisible(), 'Mobile export icon remains visible');
    await page.locator('#sidebarToggle').click();
    await page.locator('#historyList .chat-item').first().click();
    await page.waitForFunction(() => !document.querySelector('.app-shell').classList.contains('sidebar-open'));
    await page.setViewportSize({width: 1440, height: 900});
    await page.waitForFunction(() => document.querySelector('#sidebarToggle').getAttribute('aria-expanded') === 'true');
    await page.keyboard.press('Escape');
    assert(await page.locator('#sidebarToggle').getAttribute('aria-expanded') === 'true', 'Desktop Escape preserves visible sidebar ARIA');
    await page.setViewportSize({width: 390, height: 844});
    await page.waitForFunction(() => document.querySelector('#sidebarToggle').getAttribute('aria-expanded') === 'false');
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    assert(!overflow, 'No horizontal page overflow');
    assert(errors.length === 0, JSON.stringify(errors));
    fs.writeFileSync(path.join(out, 'browser-results.json'), JSON.stringify({home, chatting, requests: requests.length, pageErrors: errors, overflow, backend: 'mock responses; real PyScript DOM and handlers'}, null, 2));
    console.log('PASS: real PyScript desktop/mobile layout and chat flow; mocked backend');
  } catch (error) {
    await page.screenshot({path: path.join(out, 'browser-failure.png')});
    console.error((await page.locator('body').innerText()).slice(0, 3500));
    console.error(errors);
    throw error;
  } finally { await browser.close(); }
})().catch(error => {console.error(error); process.exitCode = 1;});
